import { describe, expect, it } from "vitest";
import type { FetchResult } from "../../src/fetchers/index.js";
import { renderMarkdown } from "../../src/renderers/markdown.js";

const EMPTY: FetchResult = {
  timestamp: "2026-11-27T00:00:00.000Z",
  runtimes: [],
  npm: [],
  pip: [],
  docker: [],
  github: [],
  ai_models: [],
};

describe("renderMarkdown", () => {
  it("emits the header and footer but no sections for empty data", () => {
    const md = renderMarkdown(EMPTY);

    expect(md.startsWith("# Version Reference\n")).toBe(true);
    expect(md).toContain("> Last updated: 2026-11-27T00:00:00.000Z");
    expect(md).not.toContain("## npm Packages");
    expect(md).not.toContain("## Docker Images");
    expect(md.trimEnd().endsWith("*Generated by [versionlens](https://github.com/CCicek22/versionlens)*")).toBe(true);
  });

  it("renders one table row per package with name and version", () => {
    const md = renderMarkdown({
      ...EMPTY,
      npm: [{ name: "commander", version: "15.1.0" }],
      pip: [{ name: "six", version: "1.17.0" }],
    });

    expect(md).toContain("## npm Packages");
    expect(md).toContain("| commander | 15.1.0 |");
    expect(md).toContain("## pip Packages");
    expect(md).toContain("| six | 1.17.0 |");
  });

  it("renders docker digests, using '-' when the digest is empty", () => {
    const md = renderMarkdown({
      ...EMPTY,
      docker: [
        { name: "postgres", tag: "17.12 / 17.12-alpine", digest: "sha256:abcdef01" },
        { name: "nginx", tag: "latest", digest: "" },
      ],
    });

    expect(md).toContain("| postgres | 17.12 / 17.12-alpine | sha256:abcdef01 |");
    expect(md).toContain("| nginx | latest | - |");
  });

  it("renders each AI provider with a model table", () => {
    const md = renderMarkdown({
      ...EMPTY,
      ai_models: [
        {
          provider: "Anthropic",
          models: [{ id: "claude-sonnet-4-6", name: "Claude Sonnet 4.6", context: "200K" }],
        },
      ],
    });

    expect(md).toContain("### Anthropic");
    expect(md).toContain("| Claude Sonnet 4.6 | claude-sonnet-4-6 | 200K |");
  });

  it("renders runtimes and GitHub sections only when they have entries", () => {
    const md = renderMarkdown({
      ...EMPTY,
      runtimes: [{ name: "Node.js", version: "26.13.1 (LTS)" }],
      github: [{ name: "acme/tool", version: "2.3.0" }],
    });

    expect(md).toContain("| Node.js | 26.13.1 (LTS) |");
    expect(md).toContain("| acme/tool | 2.3.0 |");
    expect(md).not.toContain("## pip Packages");
  });
});
